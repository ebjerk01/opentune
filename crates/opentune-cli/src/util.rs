//! Small helpers shared by several commands.
use anyhow::{Context, Result};
use opentune_core::Progress;

pub fn parse_num(s: &str) -> Result<u32> {
    let s = s.trim();
    if let Some(hex) = s.strip_prefix("0x") {
        u32::from_str_radix(hex, 16).with_context(|| format!("bad hex: {s}"))
    } else {
        s.parse::<u32>().with_context(|| format!("bad number: {s}"))
    }
}

pub fn noprogress(_: Progress) {}
